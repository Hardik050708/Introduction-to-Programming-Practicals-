# Practical 2 - Practice Question 4: Arithmetic operators

a, b = 25, 4
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Float division:", a / b)  # / keeps the fractional quotient.
print("Floor division:", a // b)  # // rounds the quotient down.
print("Remainder:", a % b)
print("Power:", a ** b)

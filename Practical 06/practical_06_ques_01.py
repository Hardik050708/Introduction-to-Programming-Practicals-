# Practical 6 - Question 1: Create and access a 2D list

# I create a matrix as a list of rows and access values by row and column.

# The question uses row 2, column 3; Python uses indices [1][2].

matrix = [[1, 2, 3], [4, 5, 6], [7, 8, 9]]

# I display the result clearly.
print('Matrix:', matrix)
print('First row:', matrix[0])
print('Element at row 2, column 3:', matrix[1][2])

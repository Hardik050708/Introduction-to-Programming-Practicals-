# Practical 7 - Question 7: Sort and reverse

# I sort the list in both orders and then reverse its current order.

numbers = [4, 1, 3, 2]

# I sort the list in the required order.
numbers.sort()

# I display the result clearly.
print('Ascending:', numbers)

# I sort the list in the required order.
numbers.sort(reverse=True)

# I display the result clearly.
print('Descending:', numbers)

# I reverse the order of the existing list.
numbers.reverse()

# I display the result clearly.
print('Reversed descending list:', numbers)

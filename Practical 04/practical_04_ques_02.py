# Practical 4 - Question 2: While loop

# I update the while-loop counter so the loop stops after 10.

number = 1

# I repeat the steps until the stopping condition is reached.
while number <= 10:
    print(number, end=' ')
    number += 1

# I display the result clearly.
print('\nEquivalent for loop:')

# I repeat this step for each value in the sequence.
for number in range(1, 11):
    print(number, end=' ')

# I display the result clearly.
print()
